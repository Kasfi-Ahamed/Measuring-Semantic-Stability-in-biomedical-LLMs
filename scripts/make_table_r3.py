"""Regenerate Table R3 (CADEC selective risk at fixed coverage) from the curve artefact.

WHY A SCRIPT. Table R3 in docs/RQ4_CADEC_results.md and S8 in docs/SUPPLEMENTARY.md both
cited outputs/rq3/rq4_risk_coverage_operating_points_cadec.csv, dated 2026-09-15 -- before the
cut-off corpus (2026-09-19) and before the RQ4 re-run (job 34433, 2026-09-21). The numbers
happened to agree to 0.0038, but a manuscript table pointing at a stale file is a table nobody
can re-derive. This emits the table from the CURRENT artefact so "recompute R3" is a command
rather than a morning's work.

SOURCE: outputs/rq4/rq4_risk_coverage_margin_cadec.csv, written by job 34433. The three
operating points are EXACT grid values on its coverage axis (0.50, 0.75, 0.90), so no
interpolation happens and none is hidden.

Validated against a second, independent path: scripts/rq4_bootstrap_calibrate.py --full
computes the same operating points inside its own bootstrap and agrees to 0.000000 at all
three levels for all 8 models and both reported signals (docs/BUG_AUDIT.md 18).

Usage:  scripts/make_table_r3.py [--check]      --check compares against the doc and exits
                                                 non-zero if they disagree
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "outputs/rq4/rq4_risk_coverage_margin_cadec.csv"
DOC = ROOT / "docs/RQ4_CADEC_results.md"
COVERAGES = [0.90, 0.75, 0.50]
SIGNALS = ["entropy", "confidence", "margin", "combined_3"]
MODEL_ORDER = ["BERT-base", "BioBERT", "PubMedBERT", "FLAN-T5-base", "BioMistral-7B",
               "Mistral-7B-Instruct-v0.1", "Llama3-OpenBioLLM-8B", "Meta-Llama-3-8B-Instruct"]


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def build() -> list[str]:
    d = pd.read_csv(SRC)
    grid = sorted(d["coverage"].unique())
    for c in COVERAGES:
        if not any(abs(g - c) < 1e-9 for g in grid):
            raise SystemExit(f"coverage {c} is not an exact grid point; would need "
                             f"interpolation. Grid: {grid}")
    missing_m = [m for m in MODEL_ORDER if m not in set(d["model"])]
    missing_s = [s for s in SIGNALS if s not in set(d["signal"])]
    if missing_m or missing_s:
        raise SystemExit(f"absent from {SRC.name}: models={missing_m} signals={missing_s}")
    p = d.pivot_table(index=["model", "signal"], columns="coverage", values="risk")
    out = ["| model | signal | 90% | 75% | 50% |", "|---|---|---:|---:|---:|"]
    for m in MODEL_ORDER:
        for s in SIGNALS:
            r = p.loc[(m, s)]
            out.append(f"| {m} | {s} | {r[0.90]:.4f} | {r[0.75]:.4f} | {r[0.50]:.4f} |")
    return out


def current_from_doc() -> list[str]:
    txt = DOC.read_text().split("\n")
    i = next(k for k, l in enumerate(txt) if l.startswith("| model | signal | 90%"))
    j = i
    while j < len(txt) and txt[j].startswith("|"):
        j += 1
    return txt[i:j]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="compare the doc against the artefact; exit 1 if they differ")
    a = ap.parse_args()
    rows = build()
    if a.check:
        cur = current_from_doc()
        if cur == rows:
            print(f"Table R3 matches {SRC.name} (sha256 {sha256(SRC)[:16]}...)")
            return 0
        print("Table R3 DIFFERS from the artefact:")
        for k, (x, y) in enumerate(zip(cur + [""] * len(rows), rows + [""] * len(cur))):
            if x != y:
                print(f"  doc      : {x}")
                print(f"  artefact : {y}")
        return 1
    print(f"<!-- GENERATED by scripts/make_table_r3.py from "
          f"outputs/rq4/rq4_risk_coverage_margin_cadec.csv")
    print(f"     sha256 {sha256(SRC)}")
    print(f"     Regenerate:  scripts/make_table_r3.py")
    print(f"     Verify:      scripts/make_table_r3.py --check   -->")
    print("\n".join(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
